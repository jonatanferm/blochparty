"""The README's layout table, generated from the package's module docstrings.

    uv run python tools/layout.py           # rewrite the table in README.md (between the layout markers)
    uv run python tools/layout.py --check   # exit 1 if README.md's table is not what the docstrings say

One row per top-level module or package of ``src/blochparty`` (the forwarding modules that keep old import paths
working are left out): its name, the first sentence of its docstring and, for a package, its modules.
``tests/docs/test_docs.py`` runs the check, so a module's summary and the README cannot drift apart.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "blochparty"
README = ROOT / "README.md"
BEGIN, END = "<!-- layout: generated by tools/layout.py from the module docstrings -->", "<!-- /layout -->"


def _first_sentence(doc: str) -> str:
    para = " ".join(doc.strip().split("\n\n")[0].split())
    m = re.search(r"\.(\s|$)", para)
    text = para[:m.start() + 1] if m else para
    return text.replace("``", "`").replace("|", "\\|")


def _forwards(source: str) -> bool:
    """A module that replaces itself in sys.modules by the one it moved to."""
    return "sys.modules[__name__] =" in source


def rows() -> list[tuple[str, str]]:
    out = []
    for p in sorted(PACKAGE.iterdir()):
        if p.name.startswith("_") or p.name == "__pycache__":
            continue
        if p.is_dir() and (p / "__init__.py").exists():
            src = (p / "__init__.py").read_text()
            if _forwards(src):
                continue
            subs = sorted(q.stem if q.is_file() else q.name for q in p.iterdir()
                          if not q.name.startswith("_") and (q.suffix == ".py" or (q.is_dir() and (q / "__init__.py").exists())))
            text = _first_sentence(ast.get_docstring(ast.parse(src)) or "")
            out.append((f"`{p.name}/`", text + (" Modules: " + ", ".join(f"`{s}`" for s in subs) + "." if subs else "")))
        elif p.suffix == ".py":
            src = p.read_text()
            if _forwards(src):
                continue
            out.append((f"`{p.name}`", _first_sentence(ast.get_docstring(ast.parse(src)) or "")))
    return out


def table() -> str:
    lines = ["| module | contents |", "|---|---|"] + [f"| {name} | {text} |" for name, text in rows()]
    return "\n".join([BEGIN, *lines, END])


def render(readme: str) -> str:
    start, stop = readme.index(BEGIN), readme.index(END) + len(END)
    return readme[:start] + table() + readme[stop:]


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = README.read_text()
    new = render(text)
    if "--check" in argv:
        if new != text:
            print("README.md's layout table is stale: run uv run python tools/layout.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
